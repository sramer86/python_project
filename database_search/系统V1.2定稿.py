    def export_to_excel(self):
        if not self.temp_storage:
            messagebox.showwarning("提示", "当前没有数据可以导出！")
            return

        # 1. 弹出文件保存对话框
        file_path = filedialog.asksaveasfilename(
            title="保存数据表",
            defaultextension=".xlsx",
            filetypes=[("Excel 工作簿", "*.xlsx")],
            initialfile="元器件录入数据.xlsx"
        )
        
        if not file_path: # 用户点击了取消
            return

        try:
            # 2. 动态获取所有可能的表头
            all_headers = []
            for item in self.temp_storage:
                for key in item.keys():
                    if key not in all_headers:
                        all_headers.append(key)

            # 3. 创建 Excel 工作簿
            wb = openpyxl.Workbook()
            ws = wb.active
            ws.title = "元器件录入数据"

            # 4. 写入表头并设置样式
            header_font = openpyxl.styles.Font(bold=True, color="FFFFFF")
            header_fill = openpyxl.styles.PatternFill(start_color="4472C4", end_color="4472C4", fill_type="solid")
            
            for col_idx, header in enumerate(all_headers, start=1):
                cell = ws.cell(row=1, column=col_idx, value=header)
                cell.font = header_font
                cell.fill = header_fill
                cell.alignment = openpyxl.styles.Alignment(horizontal='center')

            # 5. 写入数据行
            for row_idx, item in enumerate(self.temp_storage, start=2):
                for col_idx, header in enumerate(all_headers, start=1):
                    ws.cell(row=row_idx, column=col_idx, value=item.get(header, ""))

            # 6. 自动调整列宽 (简易版)
            for col_idx, header in enumerate(all_headers, start=1):
                max_len = len(str(header))
                for row in range(2, len(self.temp_storage) + 2):
                    val_len = len(str(ws.cell(row=row, column=col_idx).value or ""))
                    max_len = max(max_len, val_len)
                ws.column_dimensions[openpyxl.utils.get_column_letter(col_idx)].width = min(max_len + 4, 40)

            wb.save(file_path)
            messagebox.showinfo("成功", f"数据已成功导出至：\n{file_path}")

        except Exception as e:
            messagebox.showerror("导出失败", f"发生错误：{str(e)}")

