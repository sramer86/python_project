    def refresh_tree(self):
        for item in self.tree.get_children():
            self.tree.delete(item)
        for index, row in enumerate(self.temp_storage, start=1):
            other_params = " | ".join([
                f"{k}:{v}" for k, v in row.items() 
                if k not in ["大类", "详细分类", "公司料号", "物资名称", "简称"]
            ])
            self.tree.insert("", tk.END, values=(
                index,                  
                row.get("大类"), 
                row.get("详细分类"), 
                row.get("公司料号"), 
                row.get("物资名称"), 
                row.get("简称"), 
                other_params
            ))

