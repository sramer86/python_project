    # 第二页：数据录入
    # ==========================================
    def go_to_entry_page(self):
        cat, detail = self.combo_category.get(), self.combo_detail.get()
        if not cat or not detail:
            messagebox.showwarning("提示", "请先完成所有的分类选择！")
            return
        self.show_entry_page(cat, detail)

    def show_entry_page(self, category, detail, prefill_data=None):
        # 1. 清空页面容器
        for w in self.page_container.winfo_children(): 
            w.destroy()

        self.create_global_nav_button(self.page_container)

        content_frame = ttk.Frame(self.page_container)
        content_frame.pack(fill=tk.BOTH, expand=True)

        mode_text = "修改数据" if self.editing_index != -1 else "录入新数据"
        ttk.Label(content_frame, text=f"步骤 2: {mode_text} - {category}", font=("Microsoft YaHei", 18, "bold")).pack(pady=(0, 20))

       
        # ==========================================
        # 【核心滚动区域】(Canvas + 双 Scrollbar)
        # ==========================================
        
        # 1. 创建 Canvas
        canvas = tk.Canvas(content_frame, borderwidth=0, highlightthickness=0)
        
        # 2. 创建垂直滚动条 (Y轴)
        scrollbar_y = ttk.Scrollbar(content_frame, orient="vertical", command=canvas.yview)
        
        # 3. 创建水平滚动条 (X轴)
        scrollbar_x = ttk.Scrollbar(content_frame, orient="horizontal", command=canvas.xview)
        
        # 4. 创建内部容器 (所有的表单内容都放在这个 frame 里)
        scrollable_frame = ttk.Frame(canvas)

        # --- 关键配置：双向绑定 ---
        
        # A. 将滚动条的控制命令绑定给 Canvas
        canvas.configure(yscrollcommand=scrollbar_y.set, xscrollcommand=scrollbar_x.set)
        
        # B. 当内部内容大小改变时，更新 Canvas 的滚动区域
        def _on_frame_configure(event):
            canvas.configure(scrollregion=canvas.bbox("all"))
        scrollable_frame.bind("<Configure>", _on_frame_configure)

        # C. 【重要】当 Canvas 宽度改变时，强制让内部 Frame 跟随变宽
        # 这样能保证内容始终填满窗口宽度，只有内容真正超出时才出现水平滚动条
        def _on_canvas_configure(event):
            canvas.itemconfig("inner_frame", width=event.width)
        canvas.bind("<Configure>", _on_canvas_configure)

        # D. 将 Frame 放入 Canvas
        canvas.create_window((0, 0), window=scrollable_frame, anchor="nw", tags="inner_frame")

        # --- 布局管理 (Pack) ---
        # 注意顺序和 fill 属性，这决定了滚动条是否好用
        
        # 1. 垂直滚动条靠右，填满 Y 轴
        scrollbar_y.pack(side="right", fill="y")
        
        # 2. 水平滚动条靠下，填满 X 轴
        # fill="x" 保证它能被鼠标完整点击和拖动
        scrollbar_x.pack(side="bottom", fill="x")
        
        # 3. Canvas 占据剩余所有空间
        canvas.pack(side="left", fill="both", expand=True)


        # ==========================================
        # 【鼠标滚轮绑定】(仅控制垂直滚动)
        # ==========================================
        def _on_mousewheel(event):
            # Windows/Linux 下 event.delta 通常为 120 或 -120
            # Mac 下可能需要不同的处理，这里使用通用的 Windows 逻辑
            canvas.yview_scroll(int(-1 * (event.delta / 120)), "units")
            
        # 绑定到 Canvas 上，或者绑定到 scrollable_frame 上以确保焦点正确
        # bind_all 是全局生效，如果你想只在鼠标在窗口内时生效，可以用 canvas.bind
        canvas.bind_all("<MouseWheel>", _on_mousewheel)
        # ==========================================
        # 后续表单初始化
        # ==========================================
        form_frame = scrollable_frame
        form_frame.columnconfigure(1, weight=1) 

        self.entry_widgets = {}
        row_index = 0
        # --- 3. 动态插入示例数据显示区域 (优化版) ---
        example_data = EXAMPLE_DATA.get(category, {})
        if example_data:
            # 【优化1】减小 padding，从 10 改为 5
            example_label_frame = ttk.LabelFrame(form_frame, text="📌 填写参考", padding=5)
            example_label_frame.grid(row=row_index, column=0, columnspan=2, sticky=tk.EW, pady=(0, 10), padx=5)
            
            ex_row = 0
            ex_col = 0
            
            # 定义一个小号灰色字体
            small_gray_font = ("Microsoft YaHei", 8) 

            for key, val in example_data.items():
                # 【优化2】设置 font 参数减小字号，foreground 保持灰色
                ttk.Label(
                    example_label_frame, 
                    text=f"{key}: {val}", 
                    foreground="gray",
                    font=small_gray_font 
                ).grid(
                    row=ex_row, 
                    column=ex_col, 
                    sticky=tk.W, 
                    padx=5,   # 增加一点左右间距防止文字粘连
                    pady=1    # 【优化3】减小垂直间距，从 2 改为 1
                )
                
                # 【优化4】双列布局逻辑：每行显示两个，超过后换行
                # 如果你希望保持单列但更紧凑，可以删掉下面这4行，只保留 ex_row += 1
                ex_col += 1
                if ex_col > 1:  # 每行显示2个 (索引0和1)
                    ex_col = 0
                    ex_row += 1
            
            row_index += 1

        # --- 4. 详细分类（只读） ---
        ttk.Label(form_frame, text="详细分类:", font=("Microsoft YaHei", 14, "bold")).grid(row=row_index, column=0, sticky=tk.W, pady=5)
        entry_detail_fixed = ttk.Entry(form_frame)
        entry_detail_fixed.insert(0, detail)
        entry_detail_fixed.config(state="readonly")
        entry_detail_fixed.grid(row=row_index, column=1, sticky=tk.EW, padx=5, pady=5)
        row_index += 1

        # --- 5. 动态生成表单字段 ---
        fields = FORM_SCHEMA.get(category, [])
        category_options = FIELD_OPTIONS.get(category, {})

        for field_name in fields:
            ttk.Label(form_frame, text=f"{field_name}:").grid(row=row_index, column=0, sticky=tk.W, pady=5)
            
            # A. 处理质量保证等级联动
